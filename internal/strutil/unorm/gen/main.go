// Command gen writes tables_gen.go, the normalization data of package unorm.
// Run it in internal/strutil/unorm:
//
//	go run ./gen [-ucd DIR]
//
// The tables are computed from the Unicode Character Database of Unicode 17.0.0,
// the version Node 24's ICU 78 implements: the combining classes and canonical
// decomposition mappings of UnicodeData.txt and the Full_Composition_Exclusion
// property of DerivedNormalizationProps.txt. The files are downloaded from
// unicode.org unless -ucd names a local directory holding them.
package main

import (
	"flag"
	"fmt"
	"log"
	"slices"
	"strconv"
	"strings"

	"github.com/edge-js/edge-go/internal/tablegen"
)

const unicodeVersion = "17.0.0"

// The Hangul syllables, which normalization decomposes and composes
// arithmetically (Unicode §3.12), are left out of the tables.
const (
	hangulFirst = 0xAC00
	hangulLast  = 0xAC00 + 11172 - 1
)

func main() {
	ucd := flag.String("ucd", "https://www.unicode.org/Public/"+unicodeVersion+"/ucd",
		"directory or URL of the Unicode "+unicodeVersion+" Character Database")
	out := flag.String("o", "tables_gen.go", "output file")
	flag.Parse()

	ccc := map[rune]uint8{}
	mappings := map[rune][]rune{}
	err := tablegen.ReadRecords(*ucd+"/UnicodeData.txt", func(fields []string) error {
		c, err := tablegen.ParseCodePoint(fields[0])
		if err != nil {
			return err
		}
		class, err := strconv.ParseUint(fields[3], 10, 8)
		if err != nil {
			return err
		}
		if class != 0 {
			ccc[c] = uint8(class)
		}
		// A mapping with a <tag> is a compatibility decomposition.
		if m := fields[5]; m != "" && !strings.HasPrefix(m, "<") {
			if mappings[c], err = tablegen.ParseCodePoints(m); err != nil {
				return err
			}
		}
		return nil
	})
	if err != nil {
		log.Fatal(err)
	}
	excluded := map[rune]bool{}
	err = tablegen.ReadRecords(*ucd+"/DerivedNormalizationProps.txt", func(fields []string) error {
		if fields[1] != "Full_Composition_Exclusion" {
			return nil
		}
		lo, hi, err := tablegen.ParseRange(fields[0])
		for c := lo; c <= hi && err == nil; c++ {
			excluded[c] = true
		}
		return err
	})
	if err != nil {
		log.Fatal(err)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen/main.go from the Unicode %s Character Database; DO NOT EDIT.\n\n", unicodeVersion)
	b.WriteString("package unorm\n\n")
	b.WriteString("// combiningClass holds the code points whose Canonical_Combining_Class is not 0.\n")
	b.WriteString("var combiningClass = map[rune]uint8{\n")
	for _, c := range sortedKeys(ccc) {
		fmt.Fprintf(&b, "\t%s: %d,\n", hex(c), ccc[c])
	}
	b.WriteString("}\n\n")
	b.WriteString("// decompositions maps a code point to its full canonical decomposition, the\n")
	b.WriteString("// Hangul syllables (decomposed arithmetically) excepted.\n")
	b.WriteString("var decompositions = map[rune][]rune{\n")
	for _, c := range sortedKeys(mappings) {
		if c >= hangulFirst && c <= hangulLast {
			continue
		}
		d := decompose(c, mappings, ccc)
		parts := make([]string, len(d))
		for i, r := range d {
			parts[i] = hex(r)
		}
		fmt.Fprintf(&b, "\t%s: {%s},\n", hex(c), strings.Join(parts, ", "))
	}
	b.WriteString("}\n\n")
	b.WriteString("// compositions maps the two code points of a primary composite's canonical\n")
	b.WriteString("// mapping to the composite, the Hangul syllables excepted.\n")
	b.WriteString("var compositions = map[[2]rune]rune{\n")
	for _, c := range sortedKeys(mappings) {
		if m := mappings[c]; len(m) == 2 && !excluded[c] {
			fmt.Fprintf(&b, "\t{%s, %s}: %s,\n", hex(m[0]), hex(m[1]), hex(c))
		}
	}
	b.WriteString("}\n")
	if err := tablegen.WriteGo(*out, []byte(b.String())); err != nil {
		log.Fatal(err)
	}
}

// decompose returns the full canonical decomposition of c: its mapping applied
// recursively, then put in canonical order (a stable sort of each run of
// non-starters by combining class).
func decompose(c rune, mappings map[rune][]rune, ccc map[rune]uint8) []rune {
	var out []rune
	var expand func(r rune)
	expand = func(r rune) {
		m, ok := mappings[r]
		if !ok {
			out = append(out, r)
			return
		}
		for _, x := range m {
			expand(x)
		}
	}
	expand(c)
	for i := 0; i < len(out); {
		j := i
		for j < len(out) && ccc[out[j]] != 0 {
			j++
		}
		slices.SortStableFunc(out[i:j], func(a, b rune) int { return int(ccc[a]) - int(ccc[b]) })
		i = j + 1
	}
	return out
}

// hex writes a code point as the tables do: 0x and at least four upper-case
// hex digits.
func hex(c rune) string { return fmt.Sprintf("0x%04X", c) }

// sortedKeys returns the keys of m in ascending order.
func sortedKeys[V any](m map[rune]V) []rune {
	keys := make([]rune, 0, len(m))
	for c := range m {
		keys = append(keys, c)
	}
	slices.Sort(keys)
	return keys
}
