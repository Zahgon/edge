// Command gen writes nodeglobals_gen.go from testdata/nodeglobals.json, the names
// of the defined globals of a Node ES module that testdata/nodeglobals.mjs
// records. Run it in internal/jsrt:
//
//	go run ./gen
package main

import (
	"flag"
	"fmt"
	"log"
	"slices"
	"strings"

	"github.com/edge-js/edge-go/internal/tablegen"
)

func main() {
	in := flag.String("i", "testdata/nodeglobals.json", "the recording")
	out := flag.String("o", "nodeglobals_gen.go", "output file")
	flag.Parse()
	var recording struct {
		Node    string
		Globals []string
	}
	if err := tablegen.ReadJSON(*in, &recording); err != nil {
		log.Fatal(err)
	}
	// The names are ASCII, so byte order is the code-unit order the recorder
	// sorts by and the order slices.BinarySearch expects.
	names := slices.Clone(recording.Globals)
	slices.Sort(names)
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen/main.go from testdata/nodeglobals.json (Node %s); DO NOT EDIT.\n\n", recording.Node)
	b.WriteString("package jsrt\n\n")
	b.WriteString("// nodeGlobals holds, sorted, the names for which\n")
	b.WriteString("// `globalThis[name] !== undefined` in a Node ES module before any code runs:\n")
	b.WriteString("// the global object's own properties and those it inherits.\n")
	b.WriteString("var nodeGlobals = [...]string{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t%q,\n", name)
	}
	b.WriteString("}\n")
	if err := tablegen.WriteGo(*out, []byte(b.String())); err != nil {
		log.Fatal(err)
	}
}
