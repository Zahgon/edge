package jsrt

import "testing"

// TestAsyncGenerators checks async generator functions and methods: the
// queue of next, return and throw requests and the promises they return,
// await and yield inside the body, return values awaited, yield* over async
// and sync iterables, for await over arrays, generators and async generators
// (closing them when the loop stops early), the order of their promise jobs
// among others, the intrinsics' names and
// prototypes, and the early errors. The expected values were printed by Node
// v24.22.1.
func TestAsyncGenerators(t *testing.T) {
	runBodies(t, []bodyCase{
		{`class A { static async *gen() { yield 1 } static async am() { return 2 } static *g() { yield 3 } }; return [typeof A.gen, typeof A.am, [...A.g()].join()].join()`,
			`function,function,3`},
		{`for await (const x of 1) {}`,
			`throw TypeError: 1 is not async iterable`},
		{`for await (const x of {}) {}`,
			`throw TypeError: {} is not async iterable`},
		{`for await (const x of null) {}`,
			`throw TypeError: Cannot read properties of null (reading 'Symbol(Symbol.asyncIterator)')`},
		{`const o = { a: 1 }; for await (const x of o.a) {}`,
			`throw TypeError: o.a is not async iterable`},
		{`async function* g() { yield* 1 } for await (const x of g()) {}`,
			`throw TypeError: undefined is not a function`},
		{`function f() { for await (const x of []) {} }`,
			`throw SyntaxError: Unexpected reserved word`},
		{`for await (const x in {}) {}`,
			`throw SyntaxError: Unexpected token 'in'`},
		{`for await (;;) {}`,
			`throw SyntaxError: Unexpected token ';'`},
		{`const log = []; for await (const x of [1, Promise.resolve(2), 3]) log.push(x); return log.join()`,
			`1,2,3`},
		{`async function* g() { yield 1; yield Promise.resolve(2); return 3 } const it = g(); const r = []; for (let i = 0; i < 4; i++) r.push(JSON.stringify(await it.next())); return r.join()`,
			`{"value":1,"done":false},{"value":2,"done":false},{"value":3,"done":true},{"done":true}`},
		{`async function* g() { const x = yield 1; return x } const it = g(); const a = it.next(); const b = it.next('B'); const c = it.next(); return JSON.stringify([await a, await b, await c])`,
			`[{"value":1,"done":false},{"value":"B","done":true},{"done":true}]`},
		{`async function* g() { try { yield 1 } finally { log.push('f') } } const log = []; const it = g(); await it.next(); const r = await it.return(5); return JSON.stringify(r) + log`,
			`{"value":5,"done":true}f`},
		{`async function* g() { yield 1 } const it = g(); const r = await it.return(Promise.resolve(7)); return JSON.stringify(r) + JSON.stringify(await it.next())`,
			`{"value":7,"done":true}{"done":true}`},
		{`async function* g() { yield 1 } const it = g(); try { await it.throw(new Error('t')) } catch (e) { return e.message + JSON.stringify(await it.next()) }`,
			`t{"done":true}`},
		{`async function* g() { try { yield 1 } catch (e) { yield 'c' + e } } const it = g(); await it.next(); return JSON.stringify(await it.throw('E'))`,
			`{"value":"cE","done":false}`},
		{`async function* g() { yield* [1, 2]; yield* h(); return 'end' } async function* h() { yield 'h1'; return 'hr' } const out = []; for await (const x of g()) out.push(x); return out.join()`,
			`1,2,h1`},
		{`async function* g() { const r = yield* h(); yield r } async function* h() { yield 'h1'; return 'hr' } const out = []; for await (const x of g()) out.push(x); return out.join()`,
			`h1,hr`},
		{`async function* g() { yield 1 } return Object.prototype.toString.call(g) + Object.prototype.toString.call(g()) + typeof g().next + String(g)`,
			`[object AsyncGeneratorFunction][object AsyncGenerator]functionasync function* g() { yield 1 }`},
		{`async function* g() {} const AGF = Object.getPrototypeOf(g).constructor; return AGF.name + AGF.length + String(new AGF('a', 'yield a'))`,
			`AsyncGeneratorFunction1async function* anonymous(a
) {
yield a
}`},
		{`async function* g() { yield 1 } const AGP = Object.getPrototypeOf(g.prototype); return Object.getOwnPropertyNames(AGP).join() + Object.getOwnPropertyNames(Object.getPrototypeOf(AGP)).join()`,
			`constructor,next,return,throw`},
		{`async function* g() {} return String(g.prototype instanceof Object) + Object.getOwnPropertyNames(g).join() + (Object.getPrototypeOf(g()) === g.prototype)`,
			`truelength,name,prototypetrue`},
		{`async function* g() {} new g()`,
			`throw TypeError: g is not a constructor`},
		{`async function* g() {} const AGP = Object.getPrototypeOf(g.prototype); try { await AGP.next.call({}) } catch (e) { return e.message }`,
			`Method [AsyncGenerator].prototype.next called on incompatible receiver #<Object>`},
		{`const order = []; async function* g() { order.push('start'); yield 1; order.push('after') } const it = g(); const p = it.next(); order.push('sync'); await p; return order.join()`,
			`start,sync`},
		{`async function* g() { for await (const x of [Promise.resolve('a'), 'b']) yield x + '!' } const out = []; for await (const x of g()) out.push(x); return out.join()`,
			`a!,b!`},
		{`const log = []; async function* g() { try { yield 1; yield 2 } finally { log.push('closed') } } for await (const x of g()) { log.push(x); break } return log.join()`,
			`1,closed`},
		{`const log = []; function* s() { try { yield 1; yield 2 } finally { log.push('sclosed') } } for await (const x of s()) { log.push(x); break } return log.join()`,
			`1,sclosed`},
		{`async function* g() { yield 1; yield 2 } const it = g(); const ps = [it.next(), it.next(), it.next(), it.return(9), it.next()]; const r = []; for (const p of ps) r.push(JSON.stringify(await p)); return r.join()`,
			`{"value":1,"done":false},{"value":2,"done":false},{"done":true},{"value":9,"done":true},{"done":true}`},
		{`async function* g() { await null; throw new Error('boom') } const it = g(); try { await it.next() } catch (e) { return e.message + JSON.stringify(await it.next()) }`,
			`boom{"done":true}`},
		{`async function* g() { yield 1 } const it = g(); await it.next(); await it.next(); return JSON.stringify(await it.return(Promise.reject(new Error('rj')).catch(e => e.message)))`,
			`{"value":"rj","done":true}`},
		{`async function* g() { yield Promise.reject(new Error('yr')) } const it = g(); try { await it.next() } catch (e) { return e.message + JSON.stringify(await it.next()) }`,
			`yr{"done":true}`},
		{`async function* g() { return Promise.resolve('rv') } return JSON.stringify(await g().next())`,
			`{"value":"rv","done":true}`},
		{`const o = { async *m() { yield 'm' } }; for await (const x of o.m()) return x + String(o.m)`,
			`masync *m() { yield 'm' }`},
		{`class A { static async *gen() { yield 'g' } } for await (const x of A.gen()) return x`,
			`g`},
		{`async function* g() { yield* { next() {} } } for await (const x of g()) {}`,
			`throw TypeError: undefined is not a function`},
		{`function* s() { yield 1 } async function* g() { yield* s() } const it = g(); await it.next(); try { await it.throw('x') } catch (e) { return String(e) }`,
			`x`},
		{`async function* g() { yield 1 } const it = g(); it.next(); return String(it)`,
			`[object AsyncGenerator]`},
		{`(async function*(){ yield await 1 })().next().then(r => r.value)`,
			`(undefined) undefined`},
		{`inspect:return (async function* ag() {})`,
			`[AsyncGeneratorFunction: ag]`},
		{`inspect:return (async function* ag() {})()`,
			`Object [AsyncGenerator] {}`},
		{`inspect:return { async *m() {} }`,
			`{ m: [AsyncGeneratorFunction: m] }`},
		{`class A { static async m() {} get g() { return 1 } set s(v) {} *gen() {} async *ag() {} ['comp' + 'uted']() {} #p() {} static p() { return new A().#p } } const d = Object.getOwnPropertyDescriptors(A.prototype); return [A.m, d.g.get, d.s.set, A.prototype.gen, A.prototype.ag, A.prototype.computed, A.p()].map(String).join(' | ')`,
			`async m() {} | get g() { return 1 } | set s(v) {} | *gen() {} | async *ag() {} | ['comp' + 'uted']() {} | #p() {}`},
		{`inspect:return Object.getPrototypeOf(async function* () {})`,
			`Function [AsyncGeneratorFunction] {}`},
		{`inspect:return Object.getPrototypeOf((async function* () {})())`,
			`Object [AsyncGenerator] {}`},
		{`inspect:return [function* g() {}, async () => {}, async function* () {}]`,
			`[
  [GeneratorFunction: g],
  [AsyncFunction (anonymous)],
  [AsyncGeneratorFunction (anonymous)]
]`},
		{`inspect:return Object.getPrototypeOf(async function* () {})`,
			`Function [AsyncGeneratorFunction] {}`},
		{`inspect:return Object.getPrototypeOf(Object.getPrototypeOf((async function* () {})()))`,
			`Object [AsyncGenerator] {}`},
		{`inspect:return Object.getPrototypeOf(function* () {})`,
			`Function [GeneratorFunction] {}`},
		{`inspect:return Object.getPrototypeOf(async function () {})`,
			`Function [AsyncFunction] {}`},
		{`inspect:return Object.getPrototypeOf(Object.getPrototypeOf((function* () {})()))`,
			`Object [Generator] {}`},
		{`const log = []; async function* g() { log.push('g1'); yield 1; log.push('g2'); yield 2; log.push('g3') } const it = g(); it.next().then(r => log.push('n1:' + r.value)); it.next().then(r => log.push('n2:' + r.value)); it.next().then(r => log.push('n3:' + r.done)); Promise.resolve().then(() => log.push('p1')).then(() => log.push('p2')).then(() => log.push('p3')); await null; await null; await null; await null; return log.join()`,
			`g1,g2,p1,n1:1,g3,p2,n2:2,n3:true,p3`},
		{`const log = []; async function* g() { yield 1; yield 2 } (async () => { for await (const x of g()) log.push('x' + x) })(); Promise.resolve().then(() => log.push('a')).then(() => log.push('b')).then(() => log.push('c')).then(() => log.push('d')).then(() => log.push('e')); for (let i = 0; i < 10; i++) await null; return log.join()`,
			`a,x1,b,c,x2,d,e`},
		{`const log = []; (async () => { for await (const x of [1, Promise.resolve(2)]) log.push('x' + x) })(); Promise.resolve().then(() => log.push('a')).then(() => log.push('b')).then(() => log.push('c')).then(() => log.push('d')); for (let i = 0; i < 10; i++) await null; return log.join()`,
			`a,x1,b,c,x2,d`},
		{`const log = []; async function* g() { try { yield 1 } finally { await null; log.push('fin') } } const it = g(); await it.next(); const p = it.return('r'); log.push('called'); const r = await p; log.push(JSON.stringify(r)); return log.join()`,
			`called,fin,{"value":"r","done":true}`},
		{`const log = []; async function* g() { const x = yield* inner(); log.push('got ' + x); return 'outer' } async function* inner() { const a = yield 'i1'; log.push('a=' + a); return 'ret' } const it = g(); log.push(JSON.stringify(await it.next('ignored'))); log.push(JSON.stringify(await it.next('A'))); return log.join()`,
			`{"value":"i1","done":false},a=A,got ret,{"value":"outer","done":true}`},
		{`async function* g() { yield* [Promise.resolve('p'), 'q'] } const out = []; for await (const x of g()) out.push(typeof x + x); return out.join()`,
			`stringp,stringq`},
		{`async function* g() { await Promise.reject(new Error('inner')) } const it = g(); const r = await it.next().catch(e => 'caught ' + e.message); return r + JSON.stringify(await it.next())`,
			`caught inner{"done":true}`},
		{`async function* g() { yield 1 } const it = g(); const a = it.return(1); const b = it.next(); return JSON.stringify([await a, await b])`,
			`[{"value":1,"done":true},{"done":true}]`},
		{`async function* g() { yield 1 } const it = g(); const a = it.throw(new Error('t')); const b = it.next(); try { await a } catch (e) { return e.message + JSON.stringify(await b) }`,
			`t{"done":true}`},
	})
}
