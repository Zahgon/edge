// Command gen writes tables_gen.go, the full case mappings of
// String.prototype.toUpperCase and toLowerCase that Go's simple mappings
// (unicode.ToUpper and unicode.ToLower) do not give. Run it in
// internal/jsrt/unicase:
//
//	go run ./gen [-data SpecialCasing.txt]
//
// V8 converts case through ICU, which applies the unconditional,
// language-independent entries of SpecialCasing.txt on top of the simple
// mappings of UnicodeData.txt; Go's unicode package has the latter for the same
// Unicode version (17.0.0, that of Node 24's ICU 78). The tables hold the
// SpecialCasing.txt entries without a condition whose mapping is not the simple
// one. The file is downloaded from unicode.org unless -data names a local copy.
package main

import (
	"flag"
	"fmt"
	"log"
	"slices"
	"strconv"
	"strings"
	"unicode"

	"github.com/edge-js/edge-go/internal/tablegen"
)

const unicodeVersion = "17.0.0"

func main() {
	data := flag.String("data", "https://www.unicode.org/Public/"+unicodeVersion+"/ucd/SpecialCasing.txt",
		"SpecialCasing.txt of Unicode "+unicodeVersion+": a path or a URL")
	out := flag.String("o", "tables_gen.go", "output file")
	flag.Parse()
	if unicode.Version != unicodeVersion {
		log.Fatalf("Go's unicode package is Unicode %s, not %s", unicode.Version, unicodeVersion)
	}
	upper, lower := map[rune]string{}, map[rune]string{}
	err := tablegen.ReadRecords(*data, func(fields []string) error {
		// code; lower; title; upper; (condition_list;)?
		if len(fields) > 5 && fields[4] != "" {
			return nil
		}
		c, err := tablegen.ParseCodePoint(fields[0])
		if err != nil {
			return err
		}
		lo, err := tablegen.ParseCodePoints(fields[1])
		if err != nil {
			return err
		}
		up, err := tablegen.ParseCodePoints(fields[3])
		if err != nil {
			return err
		}
		if !slices.Equal(up, []rune{unicode.ToUpper(c)}) {
			upper[c] = string(up)
		}
		if !slices.Equal(lo, []rune{unicode.ToLower(c)}) {
			lower[c] = string(lo)
		}
		return nil
	})
	if err != nil {
		log.Fatal(err)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen/main.go from Unicode %s SpecialCasing.txt; DO NOT EDIT.\n\n", unicodeVersion)
	b.WriteString("package unicase\n\n")
	writeTable(&b, "upperSpecial", `maps a code point to its full uppercase mapping where that is not
// unicode.ToUpper's single code point.`, upper)
	b.WriteString("\n")
	writeTable(&b, "lowerSpecial", `maps a code point to its full lowercase mapping where that is not
// unicode.ToLower's single code point. Final sigma is contextual and handled in
// ToLower.`, lower)
	if err := tablegen.WriteGo(*out, []byte(b.String())); err != nil {
		log.Fatal(err)
	}
}

// writeTable writes a map[rune]string variable in code point order.
func writeTable(b *strings.Builder, name, doc string, m map[rune]string) {
	fmt.Fprintf(b, "// %s %s\nvar %s = map[rune]string{\n", name, doc, name)
	keys := make([]rune, 0, len(m))
	for c := range m {
		keys = append(keys, c)
	}
	slices.Sort(keys)
	for _, c := range keys {
		fmt.Fprintf(b, "\t%#x: %s,\n", c, strconv.Quote(m[c]))
	}
	b.WriteString("}\n")
}
