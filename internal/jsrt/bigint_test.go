package jsrt

import "testing"

// TestBigInt checks BigInt literals in every radix, the operators on BigInts
// and their errors (mixing with numbers, division by zero, sizes beyond
// V8's), comparisons and equality with numbers and strings, the BigInt
// function with asIntN and asUintN, BigInt.prototype, conversions to strings,
// numbers and property keys, JSON.stringify, and what util.inspect and
// util.format print. The expected values were printed by Node v24.22.1.
func TestBigInt(t *testing.T) {
	runBodies(t, []bodyCase{
		{`return String(BigInt(1.5))`,
			`throw RangeError: The number 1.5 cannot be converted to a BigInt because it is not an integer`},
		{`return String(BigInt('abc'))`,
			`throw SyntaxError: Cannot convert abc to a BigInt`},
		{`return String(BigInt(undefined))`,
			`throw TypeError: Cannot convert undefined to a BigInt`},
		{`return String(BigInt(null))`,
			`throw TypeError: Cannot convert null to a BigInt`},
		{`return String(BigInt({}))`,
			`throw SyntaxError: Cannot convert [object Object] to a BigInt`},
		{`return String(BigInt('0x1F')) + BigInt(' 12 ') + BigInt('') + BigInt(true) + BigInt('-7')`,
			`311201-7`},
		{`return String(BigInt('-0x1'))`,
			`throw SyntaxError: Cannot convert -0x1 to a BigInt`},
		{`return String(BigInt('1e3'))`,
			`throw SyntaxError: Cannot convert 1e3 to a BigInt`},
		{`return String(BigInt(Infinity))`,
			`throw RangeError: The number Infinity cannot be converted to a BigInt because it is not an integer`},
		{`new BigInt(1)`,
			`throw TypeError: BigInt is not a constructor`},
		{`return BigInt.asIntN(8, 255n) + ',' + BigInt.asUintN(8, -1n) + ',' + BigInt.asIntN(64, 2n**63n) + ',' + BigInt.asUintN(0, 5n)`,
			`-1,255,-9223372036854775808,0`},
		{`return String(BigInt.asIntN(-1, 1n))`,
			`throw RangeError: Invalid value: not (convertible to) a safe integer`},
		{`return String(BigInt.asIntN(8, 1))`,
			`throw TypeError: Cannot convert 1 to a BigInt`},
		{`return (255n).toString(16) + (255n).toString(2) + (-255n).toString(36) + (10n).toString()`,
			`ff11111111-7310`},
		{`return (1n).toString(37)`,
			`throw RangeError: toString() radix argument must be between 2 and 36`},
		{`return BigInt.prototype.toString.call(1)`,
			`throw TypeError: BigInt.prototype.toString requires that 'this' be a BigInt`},
		{`return BigInt.prototype.valueOf.call('x')`,
			`throw TypeError: BigInt.prototype.valueOf requires that 'this' be a BigInt`},
		{`return (1234567n).toLocaleString() + (-1234n).toLocaleString() + (12n).toLocaleString()`,
			`1,234,567-1,23412`},
		{`return typeof 1n + typeof Object(1n) + Object.prototype.toString.call(1n) + Object.prototype.toString.call(Object(1n))`,
			`bigintobject[object BigInt][object BigInt]`},
		{`return 1n + 1`,
			`throw TypeError: Cannot mix BigInt and other types, use explicit conversions`},
		{`return +1n`,
			`throw TypeError: Cannot convert a BigInt value to a number`},
		{`return 1n / 0n`,
			`throw RangeError: Division by zero`},
		{`return 1n % 0n`,
			`throw RangeError: Division by zero`},
		{`return 2n ** -1n`,
			`throw RangeError: undefined must be positive`},
		{`return 1n >>> 0n`,
			`throw TypeError: BigInts have no unsigned right shift, use >> instead`},
		{`return String(7n / 2n) + (-7n / 2n) + (-7n % 2n) + (2n ** 64n) + (-5n >> 1n) + (5n << 2n) + (-1n & 255n) + (~5n) + (-(-3n)) + (6n ^ 3n) + (6n | 1n)`,
			`3-3-118446744073709551616-320255-6357`},
		{`return String(1n == 1) + (1n === 1) + (1n == '1') + (2n > 1) + (1n < 1.5) + (2n > '1') + (1n == true) + (0n == '') + (1n < 'x') + (1n >= 'x') + (10n > 9n)`,
			`truefalsetruetruetruetruetruetruefalsefalsetrue`},
		{`return JSON.stringify(1n)`,
			`throw TypeError: Do not know how to serialize a BigInt`},
		{`return JSON.stringify({ a: 1n })`,
			`throw TypeError: Do not know how to serialize a BigInt`},
		{"return `${12345678901234567890n}` + String(0x1fn) + 0o17n + 0b101n + 1_000n",
			`12345678901234567890311551000`},
		{`let x = 5n; x++; ++x; x--; x += 10n; return String(x)`,
			`16`},
		{`return String(Number(2n ** 64n)) + Number(-3n) + Number(2n**1024n)`,
			`18446744073709552000-3Infinity`},
		{`return Math.abs(1n)`,
			`throw TypeError: Cannot convert a BigInt value to a number`},
		{`return isNaN(1n)`,
			`throw TypeError: Cannot convert a BigInt value to a number`},
		{`return String(1n ? 'T' : 'F') + (0n ? 'T' : 'F') + !0n`,
			`TFtrue`},
		{`const o = { [1n]: 'a', 2n: 'b' }; return Object.keys(o).join() + o[1]`,
			`1,2a`},
		{`return String(new Map([[1n, 'x']]).get(1n)) + [1n, 2n].includes(2n) + [1n].indexOf(1n)`,
			`xtrue0`},
		{`return parseInt(15n) + parseFloat(2n)`,
			`(number) 17`},
		{`return 1n + 'x' + 2n`,
			`1x2`},
		{`return String([3n, 1n, 2n].sort())`,
			`1,2,3`},
		{`return String(BigInt(Number.MAX_SAFE_INTEGER) + 2n)`,
			`9007199254740993`},
		{`return String(BigInt.asUintN(64, -5n))`,
			`18446744073709551611`},
		{`return BigInt.name + BigInt.length + typeof BigInt.prototype + Object.getOwnPropertyNames(BigInt).join() + Object.getOwnPropertyNames(BigInt.prototype).join()`,
			`BigInt1objectlength,name,prototype,asUintN,asIntNconstructor,toLocaleString,toString,valueOf`},
		{`return 2n ** 10000000000n`,
			`throw RangeError: Maximum BigInt size exceeded`},
		{`return 1n << 10000000000n`,
			`throw RangeError: Maximum BigInt size exceeded`},
		{`return String(1n << -1n) + (8n >> -2n) + (-1n >> 1000n) + (1n >> 100000000000n)`,
			`032-10`},
		{`return String(Object(1n) + 1n) + typeof (Object(2n).valueOf())`,
			`2bigint`},
		{`return String(0n === -0n) + Object.is(0n, -0n) + (-0n).toString()`,
			`truetrue0`},
		{`return Number.isInteger(1n) + ' ' + Number.isSafeInteger(1n)`,
			`false false`},
		{`return String(1n * -1n) + (0n * -1n)`,
			`-10`},
		{`return String(BigInt('  0b11  ')) + BigInt('+12')`,
			`312`},
		{`return String(BigInt('+0x1'))`,
			`throw SyntaxError: Cannot convert +0x1 to a BigInt`},
		{`return String([1n, 2n].join('-')) + String(Array.from([1n]))`,
			`1-21`},
		{`return [10n, 9n].sort((a, b) => (a < b ? -1 : 1)).join()`,
			`9,10`},
		{`return String(5n - 'x')`,
			`throw TypeError: Cannot mix BigInt and other types, use explicit conversions`},
		{`inspect:return 10n`,
			`10n`},
		{`inspect:return [1n, -2n, Object(3n)]`,
			`[ 1n, -2n, [BigInt: 3n] ]`},
		{`inspect:return { a: 12345678901234567890n }`,
			`{ a: 12345678901234567890n }`},
		{`log:console.log('%s %d %i %j', 1n, 2n, 3n, 'x')`,
			`1n 2n 3n "x"`},
		{`log:console.log(5n, typeof 5n)`,
			`5n bigint`},
		{`inspect:return Object(10n)`,
			`[BigInt: 10n]`},
		{`return String(BigInt.prototype.toString.call(Object(5n)))`,
			`5`},
		{`return Object.prototype.toString.call(BigInt.prototype)`,
			`[object BigInt]`},
		{`return String(Object(1n) == 1n) + (Object(1n) === 1n)`,
			`truefalse`},
		{`return typeof BigInt(10)`,
			`bigint`},
		{`return String(BigInt(-0))`,
			`0`},
		{`return String(BigInt(2**60))`,
			`1152921504606846976`},
		{`return String(1n == 1.5) + (1n < 1.5) + (2n > 1.5) + (1n == NaN) + (1n < Infinity) + (1n > -Infinity) + (9007199254740993n > 9007199254740992)`,
			`falsetruetruefalsetruetruetrue`},
		{`return [1n < '1.5', 1n == '0x1', 1n == ' 1 ', 1n < '', 1n > ''].join()`,
			`false,true,true,false,true`},
		{`return String(-(2n ** 63n) >> 3n)`,
			`-1152921504606846976`},
		{`return (-7n % -2n).toString() + (7n % -2n)`,
			`-11`},
		{`return String((-1n) ** 3n) + (0n ** 0n) + ((-1n) ** 2n) + (1n ** 1000000000000n)`,
			`-1111`},
		{`return String(BigInt.asIntN(3, 25n)) + BigInt.asIntN(3, -25n) + BigInt.asUintN(3, -25n) + BigInt.asIntN(1, -1n)`,
			`1-17-1`},
		{`return String(BigInt.asUintN(2**53, 1n))`,
			`throw RangeError: Invalid value: not (convertible to) a safe integer`},
		{`return String(BigInt.asIntN(2**53, 1n))`,
			`throw RangeError: Invalid value: not (convertible to) a safe integer`},
		{`return BigInt.asIntN('8', '255')`,
			`(bigint) -1`},
		{`return String(-0x10n) + (-0o7n)`,
			`-16-7`},
		{`return 08n`,
			`throw SyntaxError: Invalid or unexpected token`},
		{`return 1.5n`,
			`throw SyntaxError: Invalid or unexpected token`},
		{`return 1e3n`,
			`throw SyntaxError: Invalid or unexpected token`},
		{`return 0n.toString()`,
			`0`},
		{`return String((123n).toString(36))`,
			`3f`},
		{`let a = 1n; a **= 3n; a <<= 2n; a >>= 1n; a &= 6n; a |= 1n; a ^= 2n; a %= 4n; a /= 1n; a -= 1n; a *= 5n; return String(a)`,
			`0`},
		{`let a = 1n; a >>>= 1n`,
			`throw TypeError: BigInts have no unsigned right shift, use >> instead`},
		{`return String(~-1n) + (-(1n))`,
			`0-1`},
		{`return String(typeof (1n + 2n))`,
			`bigint`},
		{`return [String(BigInt('9'.repeat(30))), BigInt('0b' + '1'.repeat(70)).toString(16)].join()`,
			`999999999999999999999999999999,3fffffffffffffffff`},
		{`return String(1n && 'y') + (0n || 'z') + (0n ?? 'w')`,
			`yz0`},
		{`switch (1n) { case 1: return 'num'; case 1n: return 'big' }`,
			`big`},
		{`return String(new Set([1n, 1n, 2n]).size)`,
			`2`},
		{`return String([0n].includes(-0n)) + Object.is(1n, 1n)`,
			`truetrue`},
		{`return isFinite(1n)`,
			`throw TypeError: Cannot convert a BigInt value to a number`},
		{`return Number.parseFloat('1n')`,
			`(number) 1`},
		{"return String(1n) + `${2n}` + [3n] + (4n).valueOf()",
			`1234`},
		{`return JSON.stringify([1n].map(String))`,
			`["1"]`},
		{`BigInt.prototype.toJSON = function () { return this.toString() + '!' }; return JSON.stringify({ a: 1n })`,
			`{"a":"1!"}`},
		{`return Math.max(1n, 2)`,
			`throw TypeError: Cannot convert a BigInt value to a number`},
		{`return 'x'.repeat(2n)`,
			`throw TypeError: Cannot convert a BigInt value to a number`},
		{`return [1, 2, 3].at(1n)`,
			`throw TypeError: Cannot convert a BigInt value to a number`},
		{`return 1n | 1`,
			`throw TypeError: Cannot mix BigInt and other types, use explicit conversions`},
		{`return 1n < {} `,
			`(boolean) false`},
		{`return 1n == {}`,
			`(boolean) false`},
		{`return 1n == { valueOf() { return 1n } }`,
			`(boolean) true`},
		{`return 2n > { valueOf() { return 1 } }`,
			`(boolean) true`},
		{`return String(2n > { valueOf() { return 1 } })`,
			`true`},
		{`inspect:return BigInt`,
			`[Function: BigInt]`},
		{`inspect:return 0n`,
			`0n`},
		{`inspect:return -5n`,
			`-5n`},
		{`inspect:return [Object(7n)]`,
			`[ [BigInt: 7n] ]`},
		{`log:console.log('%s|%d|%i|%f', 10n, 11n, 12n, 13n)`,
			`10n|11n|12n|13`},
		{`log:console.log('%o', 1n)`,
			`1n`},
		{`log:console.log({ big: 2n ** 70n })`,
			`{ big: 1180591620717411303424n }`},
		{`inspect:const o = Object.create(null); o.x = 1n; return o`,
			`[Object: null prototype] { x: 1n }`},
	})
}
