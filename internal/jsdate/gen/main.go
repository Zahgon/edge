// Command gen writes zonenames_gen.go from testdata/zonenames.json, the names V8
// prints for each IANA time zone's standard and daylight-saving time that
// testdata/zonenames.js records. Run it in internal/jsdate:
//
//	go run ./gen
package main

import (
	"flag"
	"fmt"
	"log"
	"strings"

	"github.com/edge-js/edge-go/internal/tablegen"
)

func main() {
	in := flag.String("i", "testdata/zonenames.json", "the recording")
	out := flag.String("o", "zonenames_gen.go", "output file")
	flag.Parse()
	var recording struct {
		Node, ICU string
		// Zones holds [zone, standard name, daylight-saving name] triples.
		Zones [][3]string
	}
	if err := tablegen.ReadJSON(*in, &recording); err != nil {
		log.Fatal(err)
	}
	// The names are numbered in the order they first appear.
	var names []string
	index := map[string]int{}
	nameIndex := func(name string) int {
		i, ok := index[name]
		if !ok {
			i = len(names)
			index[name] = i
			names = append(names, name)
		}
		return i
	}
	var rows strings.Builder
	for _, z := range recording.Zones {
		std := nameIndex(z[1])
		dst := nameIndex(z[2])
		fmt.Fprintf(&rows, "\t%q: {%d, %d},\n", z[0], std, dst)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen/main.go from testdata/zonenames.json (Node %s, ICU %s); DO NOT EDIT.\n\n", recording.Node, recording.ICU)
	b.WriteString("package jsdate\n\n")
	b.WriteString("// zoneNameList holds the distinct names of zoneNames.\n")
	b.WriteString("var zoneNameList = [...]string{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t%q,\n", name)
	}
	b.WriteString("}\n\n")
	b.WriteString("// zoneNames maps an IANA time zone to the indexes in zoneNameList of the names V8\n")
	b.WriteString("// prints for its standard and daylight-saving time.\n")
	b.WriteString("var zoneNames = map[string]zoneNamePair{\n")
	b.WriteString(rows.String())
	b.WriteString("}\n")
	if err := tablegen.WriteGo(*out, []byte(b.String())); err != nil {
		log.Fatal(err)
	}
}
