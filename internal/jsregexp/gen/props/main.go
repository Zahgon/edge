// Command props writes props_gen.go from testdata/props.json.gz, the Unicode
// property names V8 accepts in \p{...} and the code points of each property that
// testdata/props.mjs records from Node. Run it in internal/jsregexp:
//
//	go run ./gen/props
//
// The alias tables are the recorded names. The fix tables are what Node's
// membership adds to or removes from what uniprop.Derived derives from Go's
// unicode package, computed over every code point; a property where both agree
// has no entry.
package main

import (
	"flag"
	"fmt"
	"log"
	"slices"
	"strings"

	"github.com/edge-js/edge-go/internal/fixture"
	"github.com/edge-js/edge-go/internal/jsregexp/uniprop"
	"github.com/edge-js/edge-go/internal/tablegen"
)

func main() {
	in := flag.String("i", "testdata/props.json.gz", "the recording")
	out := flag.String("o", "props_gen.go", "output file")
	flag.Parse()
	var recording struct {
		Node, ICU, Unicode string
		GC, Binary, Script map[string]string
		Members            map[string][]rune
	}
	if err := fixture.DecodeGzipJSON(*in, &recording); err != nil {
		log.Fatal(err)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen/props from testdata/props.json.gz (Node %s, ICU %s, Unicode %s); DO NOT EDIT.\n\n",
		recording.Node, recording.ICU, recording.Unicode)
	b.WriteString("package jsregexp\n\n")
	writeAliases(&b, "gcAliases", "maps every General_Category name V8 accepts to its short name.", recording.GC)
	writeAliases(&b, "binaryAliases", "maps every binary property name V8 accepts to its long name.", recording.Binary)
	writeAliases(&b, "scriptAliases", "maps every Script and Script_Extensions value V8 accepts to its long name.", recording.Script)
	b.WriteString(`// propFixes completes uniprop.Derived's predicates: for a property key ("gc=Lu",
// "bin=Emoji", "sc=Latin", "scx=Latin") it lists the code point ranges, as
// lo, hi pairs, that Node 24 adds to or removes from the derived set.
var propFixes = map[string]propFix{
`)
	for _, key := range sortedKeys(recording.Members) {
		node := expand(recording.Members[key])
		derived := uniprop.Derived(key)
		var add, del []rune
		for c := rune(0); c <= 0x10FFFF; c++ {
			switch in := derived(c); {
			case node[c] && !in:
				add = appendRange(add, c)
			case !node[c] && in:
				del = appendRange(del, c)
			}
		}
		if add == nil && del == nil {
			continue
		}
		fmt.Fprintf(&b, "\t%q: {", key)
		writeRanges(&b, "add", add)
		writeRanges(&b, "del", del)
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	if err := tablegen.WriteGo(*out, []byte(b.String())); err != nil {
		log.Fatal(err)
	}
}

// writeAliases writes a map[string]string variable with its keys in order.
func writeAliases(b *strings.Builder, name, doc string, m map[string]string) {
	fmt.Fprintf(b, "// %s %s\nvar %s = map[string]string{\n", name, doc, name)
	for _, k := range sortedKeys(m) {
		fmt.Fprintf(b, "\t%q: %q,\n", k, m[k])
	}
	b.WriteString("}\n\n")
}

// writeRanges writes one field of a propFix, sixteen code points to a line, when
// there are ranges.
func writeRanges(b *strings.Builder, field string, pairs []rune) {
	if pairs == nil {
		return
	}
	fmt.Fprintf(b, "\n\t\t%s: []rune{\n", field)
	for i := 0; i < len(pairs); i += 16 {
		words := make([]string, 0, 16)
		for _, c := range pairs[i:min(i+16, len(pairs))] {
			words = append(words, fmt.Sprintf("%#x", c))
		}
		b.WriteString("\t\t\t" + strings.Join(words, ", ") + ",\n")
	}
	b.WriteString("\t\t}")
	if field == "add" {
		b.WriteString(",")
	}
}

// expand returns the code points of sorted lo, hi pairs as a set.
func expand(pairs []rune) []bool {
	set := make([]bool, 0x110000)
	for i := 0; i+1 < len(pairs); i += 2 {
		for c := pairs[i]; c <= pairs[i+1]; c++ {
			set[c] = true
		}
	}
	return set
}

// appendRange adds the code point c, which is above every code point already in
// pairs, to the lo, hi pairs.
func appendRange(pairs []rune, c rune) []rune {
	if n := len(pairs); n > 0 && pairs[n-1] == c-1 {
		pairs[n-1] = c
		return pairs
	}
	return append(pairs, c, c)
}

// sortedKeys returns the keys of m in byte order.
func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
