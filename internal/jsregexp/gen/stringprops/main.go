// Command stringprops writes stringprops_gen.go, the members of the properties of
// strings that V8 accepts in \p{...} with the v flag. Run it in
// internal/jsregexp:
//
//	go run ./gen/stringprops [-emoji DIR]
//
// UTS #51 defines the properties by the emoji data files of the Unicode version
// (17.0.0 for Node 24's ICU 78): each member of Basic_Emoji,
// Emoji_Keycap_Sequence, RGI_Emoji_Flag_Sequence, RGI_Emoji_Modifier_Sequence
// and RGI_Emoji_Tag_Sequence is a line of emoji-sequences.txt with that type, each
// member of RGI_Emoji_ZWJ_Sequence a line of emoji-zwj-sequences.txt, and
// RGI_Emoji is their union, so it is not written. emoji-data.txt decides which
// code points the generated literals show as themselves. The files are downloaded
// from unicode.org unless -emoji names a local directory holding them.
package main

import (
	"flag"
	"fmt"
	"log"
	"slices"
	"strings"

	"github.com/edge-js/edge-go/internal/tablegen"
)

const unicodeVersion = "17.0.0"

// properties lists the properties of strings in the order they are written.
var properties = []string{
	"Basic_Emoji",
	"Emoji_Keycap_Sequence",
	"RGI_Emoji_Flag_Sequence",
	"RGI_Emoji_Modifier_Sequence",
	"RGI_Emoji_Tag_Sequence",
	"RGI_Emoji_ZWJ_Sequence",
}

func main() {
	dir := flag.String("emoji", "https://www.unicode.org/Public/"+unicodeVersion,
		"directory or URL holding emoji-sequences.txt, emoji-zwj-sequences.txt and emoji-data.txt of Unicode "+unicodeVersion)
	out := flag.String("o", "stringprops_gen.go", "output file")
	flag.Parse()
	base := strings.TrimSuffix(*dir, "/")
	sequences, dataFile := base+"/emoji/", base+"/ucd/emoji/emoji-data.txt"
	if !strings.Contains(base, "://") {
		// A local directory holds the three files side by side.
		sequences, dataFile = base+"/", base+"/emoji-data.txt"
	}

	members := map[string][][]rune{}
	for _, file := range []string{"emoji-sequences.txt", "emoji-zwj-sequences.txt"} {
		err := tablegen.ReadRecords(sequences+file, func(fields []string) error {
			prop := fields[1]
			if !slices.Contains(properties, prop) {
				return fmt.Errorf("unknown property %q", prop)
			}
			if lo, hi, isRange := strings.Cut(fields[0], ".."); isRange {
				first, err := tablegen.ParseCodePoint(lo)
				if err != nil {
					return err
				}
				last, err := tablegen.ParseCodePoint(hi)
				for c := first; c <= last && err == nil; c++ {
					members[prop] = append(members[prop], []rune{c})
				}
				return err
			}
			seq, err := tablegen.ParseCodePoints(fields[0])
			members[prop] = append(members[prop], seq)
			return err
		})
		if err != nil {
			log.Fatal(err)
		}
	}
	shown, err := shownCodePoints(dataFile)
	if err != nil {
		log.Fatal(err)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen/stringprops from the Unicode %s emoji data; DO NOT EDIT.\n\n", unicodeVersion)
	b.WriteString("package jsregexp\n\n")
	b.WriteString("// stringPropertyMembers lists, separated by spaces, the code points and strings V8\n")
	b.WriteString("// matches with each property of strings but RGI_Emoji, which is their union.\n")
	b.WriteString("var stringPropertyMembers = map[string]string{\n")
	for _, prop := range properties {
		seqs := members[prop]
		slices.SortFunc(seqs, slices.Compare)
		seqs = slices.CompactFunc(seqs, slices.Equal)
		for i := 0; i < len(seqs); i += 16 {
			if i == 0 {
				fmt.Fprintf(&b, "\t%q: ", prop)
			} else {
				b.WriteString("\t\t")
			}
			words := make([]string, 0, 16)
			for _, seq := range seqs[i:min(i+16, len(seqs))] {
				words = append(words, literal(seq, shown))
			}
			b.WriteString(`"` + strings.Join(words, " "))
			if i+16 >= len(seqs) {
				b.WriteString("\",\n")
			} else {
				b.WriteString(" \" +\n")
			}
		}
	}
	b.WriteString("}\n")
	if err := tablegen.WriteGo(*out, []byte(b.String())); err != nil {
		log.Fatal(err)
	}
}

// shownCodePoints returns the code points with Emoji_Presentation,
// Extended_Pictographic or Regional_Indicator: the emoji characters that display
// on their own.
func shownCodePoints(dataFile string) (map[rune]bool, error) {
	shown := map[rune]bool{}
	for c := rune(0x1F1E6); c <= 0x1F1FF; c++ { // Regional_Indicator
		shown[c] = true
	}
	err := tablegen.ReadRecords(dataFile, func(fields []string) error {
		if fields[1] != "Emoji_Presentation" && fields[1] != "Extended_Pictographic" {
			return nil
		}
		lo, hi, err := tablegen.ParseRange(fields[0])
		for c := lo; c <= hi && err == nil; c++ {
			shown[c] = true
		}
		return err
	})
	return shown, err
}

// literal writes a sequence inside a Go string literal: printable ASCII other
// than the quote and the backslash, and the shown emoji characters, as
// themselves, joiners, selectors, tags, keycap marks and everything else
// escaped.
func literal(seq []rune, shown map[rune]bool) string {
	var b strings.Builder
	for _, c := range seq {
		switch {
		case c >= 0x20 && c < 0x7F && c != '"' && c != '\\', shown[c]:
			b.WriteRune(c)
		case c <= 0xFFFF:
			fmt.Fprintf(&b, `\u%04x`, c)
		default:
			fmt.Fprintf(&b, `\U%08x`, c)
		}
	}
	return b.String()
}
