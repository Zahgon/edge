// Command gen writes identifier_gen.go, the non-ASCII code points acorn accepts at
// the start of an identifier and inside one. Run it in internal/acorn:
//
//	go run ./gen [-data DerivedCoreProperties.txt]
//
// acorn 8.19.0's identifier tables are the ID_Start and ID_Continue properties of
// Unicode 18.0.0 (acorn adds U+200C and U+200D to the identifier characters, and
// Unicode lists both in ID_Continue), so they are read from that version's
// DerivedCoreProperties.txt, downloaded from unicode.org unless -data names a
// local copy.
package main

import (
	"flag"
	"fmt"
	"log"
	"strings"

	"github.com/edge-js/edge-go/internal/tablegen"
)

const (
	unicodeVersion = "18.0.0"
	acornVersion   = "8.19.0"
)

func main() {
	data := flag.String("data", "https://www.unicode.org/Public/"+unicodeVersion+"/ucd/DerivedCoreProperties.txt",
		"DerivedCoreProperties.txt of Unicode "+unicodeVersion+": a path or a URL")
	out := flag.String("o", "identifier_gen.go", "output file")
	flag.Parse()
	start, part, err := readProperties(*data)
	if err != nil {
		log.Fatal(err)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen/main.go from Unicode %s DerivedCoreProperties.txt (acorn %s's identifier data); DO NOT EDIT.\n\n", unicodeVersion, acornVersion)
	b.WriteString("package acorn\n\n")
	writeTable(&b, "identifierStartRanges", "lists the non-ASCII code points that start an identifier.", start)
	b.WriteString("\n")
	writeTable(&b, "identifierCharRanges", "lists the non-ASCII code points that continue an identifier.", part)
	if err := tablegen.WriteGo(*out, []byte(b.String())); err != nil {
		log.Fatal(err)
	}
}

// readProperties returns the sorted, merged non-ASCII ranges of ID_Start and
// ID_Continue.
func readProperties(name string) (start, part [][2]rune, err error) {
	sets := map[string]map[rune]bool{"ID_Start": {}, "ID_Continue": {}}
	err = tablegen.ReadRecords(name, func(fields []string) error {
		set, ok := sets[fields[1]]
		if !ok {
			return nil
		}
		lo, hi, err := tablegen.ParseRange(fields[0])
		if err != nil {
			return err
		}
		for c := max(lo, 0x80); c <= hi; c++ {
			set[c] = true
		}
		return nil
	})
	return ranges(sets["ID_Start"]), ranges(sets["ID_Continue"]), err
}

// ranges returns the code points of set as sorted inclusive ranges.
func ranges(set map[rune]bool) [][2]rune {
	var out [][2]rune
	for c := rune(0); c <= 0x10FFFF; c++ {
		if !set[c] {
			continue
		}
		if n := len(out); n > 0 && out[n-1][1] == c-1 {
			out[n-1][1] = c
		} else {
			out = append(out, [2]rune{c, c})
		}
	}
	return out
}

// writeTable writes a []codeRange variable, four ranges to a line.
func writeTable(b *strings.Builder, name, doc string, rs [][2]rune) {
	fmt.Fprintf(b, "// %s %s\nvar %s = []codeRange{\n", name, doc, name)
	for i := 0; i < len(rs); i += 4 {
		parts := make([]string, 0, 4)
		for _, r := range rs[i:min(i+4, len(rs))] {
			parts = append(parts, fmt.Sprintf("{0x%04x, 0x%04x}", r[0], r[1]))
		}
		b.WriteString("\t" + strings.Join(parts, ", ") + ",\n")
	}
	b.WriteString("}\n")
}
