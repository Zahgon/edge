// Command gen writes sources_gen.go from testdata/sources.json, the source texts
// of Edge's functions and classes that testdata/sources.mjs records from the
// built edge.js. Run it in internal/edgert:
//
//	go run ./gen
package main

import (
	"flag"
	"fmt"
	"log"
	"slices"
	"strings"

	"github.com/edge-js/edge-go/internal/jsrt/jsstr"
	"github.com/edge-js/edge-go/internal/tablegen"
)

func main() {
	in := flag.String("i", "testdata/sources.json", "the recording")
	out := flag.String("o", "sources_gen.go", "output file")
	flag.Parse()
	var recording struct {
		Edge, Node string
		Sources    map[string]string
	}
	if err := tablegen.ReadJSON(*in, &recording); err != nil {
		log.Fatal(err)
	}
	keys := make([]string, 0, len(recording.Sources))
	for k := range recording.Sources {
		keys = append(keys, k)
	}
	slices.Sort(keys)

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen/main.go from testdata/sources.json (edge.js %s on Node %s); DO NOT EDIT.\n\n", recording.Edge, recording.Node)
	b.WriteString("package edgert\n\n")
	b.WriteString("// sources holds the source text of Edge's functions and classes, keyed by\n")
	b.WriteString("// where they live: \"globals.html.attrs\", \"migrate.raise\", \"Template.reThrow\",\n")
	b.WriteString("// \"ComponentProps\", ...\n")
	b.WriteString("var sources = map[string]string{\n")
	for _, k := range keys {
		// A JSON string literal is a Go string literal with the same value.
		fmt.Fprintf(&b, "\t%s: %s,\n", jsstr.QuoteJSON(k), jsstr.QuoteJSON(recording.Sources[k]))
	}
	b.WriteString("}\n")
	if err := tablegen.WriteGo(*out, []byte(b.String())); err != nil {
		log.Fatal(err)
	}
}
